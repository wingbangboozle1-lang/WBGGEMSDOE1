#!/usr/bin/env python3
"""Stage only the public desk, retaining the existing root -> /docs/ URL layout.

The GitHub integration cannot change Pages administration (HTTP 403). A matching
layout under either the existing main/root publisher or the workflow avoids
racing publishers producing incompatible download URLs. No model/data download,
credential, training, selector, approval or contest upload operation is involved.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path
import shutil

ROOT = Path(__file__).resolve().parents[1]


def stage():
    target = ROOT / ".cache/pages"
    if target.exists():
        # Only remove this script's generated directory, never an arbitrary path.
        if not (target / ".wbg-pages-stage").is_file():
            raise ValueError("refusing to replace an unmarked Pages staging directory")
        shutil.rmtree(target)
    target.mkdir(parents=True)
    (target / ".wbg-pages-stage").write_text("generated by scripts/stage_pages.py\n")
    shutil.copytree(ROOT / "docs", target / "docs")
    shutil.copyfile(ROOT / "index.html", target / "index.html")
    (target / ".nojekyll").touch()
    card = json.loads((ROOT / "registry/run_card.json").read_text())
    copied = target / card["artifact"]
    with copied.open("rb") as stream:
        digest = hashlib.file_digest(stream, "sha256").hexdigest()
    if digest != card["raster_sha256"]:
        raise ValueError("staged research TIFF checksum differs from the frozen run card")
    tasc_card_path = ROOT / "evidence/tasc_best_arm_run_card_20261027.json"
    tasc_ok = None
    if tasc_card_path.exists():
        tasc_card = json.loads(tasc_card_path.read_text())
        tasc_copy = target / tasc_card["artifact"]
        with tasc_copy.open("rb") as stream:
            tasc_digest = hashlib.file_digest(stream, "sha256").hexdigest()
        tasc_ok = bool(tasc_digest == tasc_card["raster_sha256"])
        if not tasc_ok:
            raise ValueError("staged TASC TIFF checksum differs from its run card")
    print(json.dumps({"staged_site": str(target.relative_to(ROOT)),
        "canonical_path": "/WBGGEMSDOE1/docs/", "root_redirect": "docs/",
        "artifact_sha256": digest, "tasc_best_arm_sha256_verified": tasc_ok,
        "ok_to_submit": False}))
    return target


if __name__ == "__main__":
    stage()
